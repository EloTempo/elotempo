INSERT OR IGNORE INTO locais (id, nome, uf, pais_id, codigo_ibge, latitude, longitude, nome_busca)
SELECT id, nome, uf, pais_id, NULL, lat, lon, nome_busca FROM temp_cidades_mundo;

-- 2. Atualiza coordenadas e UF de cidades estrangeiras já cadastradas previamente que estavam sem lat/lon
UPDATE locais
SET latitude = t.lat,
    longitude = t.lon,
    uf = COALESCE(locais.uf, t.uf)
FROM temp_cidades_mundo t
WHERE locais.pais_id = t.pais_id
  AND locais.nome_busca = t.nome_busca
  AND (locais.latitude IS NULL OR locais.longitude IS NULL);

